// The driver's advertised Vulkan (vk/build.sh): a Khronos profile's capability (VK0 A's WebGPU-shaped profiles,
// bench/vulkan/profiles/) as C tables for Mesa's runtime: the device extensions, the features on (the runtime's
// flattened `vk_features`), the properties (`vk_properties`) and the formats' features. In VK1 nothing is drawn, so
// the profile is fixed at build; in time the caps follow the browser's adapter (docs/plans/graphics.md §2).
//   node vk/profile.ts <profile.json> <capability> <out.c>
import { readFileSync, writeFileSync } from 'node:fs';

const [file, cap, out] = process.argv.slice(2);
if (!file || !cap || !out) throw new Error('usage: profile.ts <profile.json> <capability> <out.c>');
type Json = string | number | boolean | Json[] | { [k: string]: Json };
const c = (JSON.parse(readFileSync(file, 'utf8')) as { capabilities: Record<string, { extensions: Record<string, number>; features: Record<string, Record<string, boolean>>; properties: Record<string, Record<string, Json>>; formats: Record<string, { VkFormatProperties: Record<string, string[]> }> }> }).capabilities[cap];
if (!c) throw new Error(`no capability ${cap} in ${file}`);

/** A profile value as a C expression: numbers as they are, booleans, enum names, flag lists ORed. */
const value = (v: Json): string =>
  typeof v === 'boolean' ? String(v) : typeof v === 'number' ? (Number.isInteger(v) ? `${v}${v > 0x7fffffff ? 'u' : ''}` : `${v}f`)
    : typeof v === 'string' ? (v.startsWith('VK_') ? v : JSON.stringify(v))
      : Array.isArray(v) && v.every((x) => typeof x === 'string') ? (v.length ? v.join(' | ') : '0') : '/* unsupported */ 0';

const lines = [
  `/* Generated by vk/profile.ts from ${file.replace(/^.*?(bench\/)/, '$1')}, capability ${cap}: don't edit. */`,
  '#include <string.h>',
  '#include "wg_private.h"',
  '',
  'const struct vk_device_extension_table wg_profile_extensions = {',
  ...Object.keys(c.extensions).sort().map((e) => `   .${e.replace(/^VK_/, '')} = true,`),
  '};',
  '',
  'void',
  'wg_profile_features(struct vk_features *f)',
  '{',
  ...Object.values(c.features).flatMap((s) => Object.entries(s).filter(([, on]) => on).map(([k]) => `   f->${k} = true;`)),
  '}',
  '',
  'void',
  'wg_profile_properties(struct vk_properties *p)',
  '{',
];
for (const [struct, members] of Object.entries(c.properties)) {
  const flat: Record<string, Json> = { ...members, ...(struct === 'VkPhysicalDeviceProperties' ? members.limits as Record<string, Json> : {}) };
  delete flat.limits;
  for (const [k, v] of Object.entries(flat)) {
    if (k === 'deviceName') lines.push(`   snprintf(p->deviceName, sizeof(p->deviceName), "%s", ${JSON.stringify(v)});`);
    else if (Array.isArray(v) && v.every((x) => typeof x === 'number')) v.forEach((x, i) => lines.push(`   p->${k}[${i}] = ${value(x)};`));
    else lines.push(`   p->${k} = ${value(v)};`);
  }
}
lines.push('}', '', 'const struct wg_format wg_profile_formats[] = {');
for (const [f, { VkFormatProperties: p }] of Object.entries(c.formats)) {
  lines.push(`   { ${f}, ${value(p.linearTilingFeatures ?? [])}, ${value(p.optimalTilingFeatures ?? [])}, ${value(p.bufferFeatures ?? [])} },`);
}
lines.push('};', `const uint32_t wg_profile_format_count = ${Object.keys(c.formats).length};`, '');
writeFileSync(out, lines.join('\n').replace('#include <string.h>', '#include <stdio.h>\n#include <string.h>'));
console.log(`${out}: ${Object.keys(c.extensions).length} extensions, ${Object.keys(c.formats).length} formats`);
